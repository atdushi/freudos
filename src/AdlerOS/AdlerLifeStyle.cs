namespace FreudOS.AdlerOS
{
    /// <summary>
    /// Стили жизни по Альфреду Адлеру, определяющие вектор сверхкомпенсации комплекса неполноценности.
    /// </summary>
    public enum AdlerLifeStyle : byte
    {
        /// <summary>
        /// Полезный обществу стиль (Здоровый баланс, дефолтное состояние до деградации безопасности).
        /// </summary>
        SociallyUseful = 0,

        /// <summary>
        /// Управляющий/Агрессивный стиль (Мгновенная сверхкомпенсация при SecurityDroppedEvent).
        /// </summary>
        Ruling = 1,
        
        /// <summary>
        /// Берущий/Паразитический стиль (Ожидание ресурсов извне).
        /// </summary>
        Getting = 2,
        
        /// <summary>
        /// Избегающий стиль (Бегство от решения жизненных задач).
        /// </summary>
        Avoiding = 3
    }
}
